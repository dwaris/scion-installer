#!/bin/bash
# Build Puzzles.app (Simon Tatham's Portable Puzzle Collection, Greg Hewgill's iOS front end) on Linux, without Xcode.
#   build.sh SRC OUT        SRC: the upstream checkout at app.json's commit; OUT: where Puzzles.app is made
# Needs THEOS (a Theos with toolchain/linux/iphone and sdks/iPhoneOS16.5.sdk). mkapps.py calls this; it can be run by hand.
#
# What stands in for Xcode, and why it is enough here: the app is Objective-C and C with its UI made in code; the only
# Interface Builder file is the launch screen and the only asset catalog is the app icon. So: the source files the
# Xcode project compiles (read from project.pbxproj), its resources, and an Info.plist with the build variables filled in.
set -euo pipefail
SRC=$(cd "${1:?usage: build.sh SRC OUT}" && pwd)
OUT=${2:?usage: build.sh SRC OUT}
THEOS=${THEOS:?set THEOS}
SDK=${SDK:-$THEOS/sdks/iPhoneOS16.5.sdk}
BIN=$THEOS/toolchain/linux/iphone/bin
MIN=14.0                                # UILaunchScreen in Info.plist (below) is iOS 14's
PBX=$SRC/Puzzles.xcodeproj/project.pbxproj
APP=$OUT/Puzzles.app
OBJ=$OUT/obj
rm -rf "$APP" "$OBJ"
mkdir -p "$APP" "$OBJ"

CFLAGS=(-target arm64-apple-ios$MIN -isysroot "$SDK" -O2 -DCOMBINED -DNS_BLOCK_ASSERTIONS=1 -I"$SRC" -w)
# the project's Sources phase; svnversion.c is generated by a release script upstream, version.c is the same thing unversioned
mapfile -t SRCS < <(grep -o '[A-Za-z0-9_]*\.[cm] in Sources' "$PBX" | sed 's/ in Sources//' | sort -u | grep -vx svnversion.c)
SRCS+=(version.c)
pids=()
for f in "${SRCS[@]}"; do
	case $f in
	*.m) extra=(-fobjc-arc -include "$SRC/Puzzles-Prefix.pch") ;;
	*) extra=(-std=gnu99) ;;
	esac
	"$BIN/clang" "${CFLAGS[@]}" "${extra[@]}" -c "$SRC/$f" -o "$OBJ/${f%.*}.o" &
	pids+=($!)
done
for p in "${pids[@]}"; do wait "$p"; done
"$BIN/clang" -target arm64-apple-ios$MIN -isysroot "$SDK" -fobjc-arc -o "$APP/Puzzles" "$OBJ"/*.o \
	-framework UIKit -framework Foundation -framework CoreGraphics -framework QuartzCore \
	-framework AudioToolbox -framework CoreText -framework WebKit
"$BIN/strip" -x "$APP/Puzzles" 2>/dev/null || true

# resources: the project's Resources phase, less what only Xcode's tools compile (handled below)
grep -o '[A-Za-z0-9_@.+-]* in Resources' "$PBX" | sed 's/ in Resources//' | sort -u |
	grep -v -e '\.xcassets$' -e '\.storyboard$' -e '^InfoPlist\.strings$' | while read -r r; do
	p=$(cd "$SRC" && find . -path ./.git -prune -o -name "$r" -type f -print | head -1)
	[ -n "$p" ] || { echo "build.sh: resource $r not found" >&2; exit 1; }
	cp "$SRC/$p" "$APP/$r"
done
mkdir -p "$APP/en.lproj" && cp "$SRC/en.lproj/InfoPlist.strings" "$APP/en.lproj/"
# the app icon, as actool would leave it: loose files named for their size, listed in CFBundleIcons
XC=$SRC/Puzzles/Images.xcassets/AppIcon.appiconset
cp "$XC/Icon-120.png" "$APP/AppIcon60x60@2x.png"
cp "$XC/Icon-180@3x.png" "$APP/AppIcon60x60@3x.png"
cp "$XC/Icon-76.png" "$APP/AppIcon76x76~ipad.png"
cp "$XC/Icon-76@2x.png" "$APP/AppIcon76x76@2x~ipad.png"

python3 -I - "$SRC/Puzzles-Info.plist" "$APP/Info.plist" "$MIN" "$PBX" <<'PY'
import plistlib, re, sys
src, dst, minos, pbx = sys.argv[1:]
p = plistlib.load(open(src, 'rb'))
proj = open(pbx).read()
ver = re.search(r'MARKETING_VERSION = ([0-9.]+);', proj).group(1)
build = re.search(r'CURRENT_PROJECT_VERSION = ([0-9.]+);', proj).group(1)
p.update({
    'CFBundleIdentifier': 'com.scion.oss.puzzles', 'CFBundleExecutable': 'Puzzles',
    'CFBundleName': 'Puzzles', 'CFBundleDisplayName': 'Puzzles',
    'CFBundleShortVersionString': ver, 'CFBundleVersion': build,
    'MinimumOSVersion': minos, 'CFBundleSupportedPlatforms': ['iPhoneOS'], 'DTPlatformName': 'iphoneos',
    'DTSDKName': 'iphoneos16.5', 'UIDeviceFamily': [1, 2], 'UIRequiredDeviceCapabilities': ['arm64'],
    'UILaunchScreen': {},
    'CFBundleIcons': {'CFBundlePrimaryIcon': {'CFBundleIconFiles': ['AppIcon60x60']}},
    'CFBundleIcons~ipad': {'CFBundlePrimaryIcon': {'CFBundleIconFiles': ['AppIcon60x60', 'AppIcon76x76']}},
})
p.pop('UILaunchStoryboardName', None)
plistlib.dump(p, open(dst, 'wb'), fmt=plistlib.FMT_BINARY)
PY
printf 'APPL????' > "$APP/PkgInfo"
# an ad-hoc signature: Scion's kernel runs unsigned code, but a code directory costs nothing and keeps
# the bundle valid for tools that look (no entitlements, no certificate, no Apple account)
"$BIN/ldid" -S "$APP/Puzzles"
rm -rf "$OBJ"
echo "build.sh: $APP ($(du -sh "$APP" | cut -f1))"
